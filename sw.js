const CACHE = 'lunaguna-static-1';

const PRECACHE = [
  './',
  './index.html',
  './styles.css',
  './boot.js',
  './app.js',
  './cycle.js',
  './i18n.js',
  './manifest.webmanifest',
  './icons/favicon.svg',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/icon-maskable-512.png',
  './icons/apple-touch-icon.png',
  './fonts/heebo-hebrew-400.woff2',
  './fonts/heebo-hebrew-500.woff2',
  './fonts/heebo-hebrew-700.woff2',
  './fonts/heebo-latin-400.woff2',
  './fonts/heebo-latin-500.woff2',
  './fonts/heebo-latin-700.woff2',
  './fonts/frank-hebrew-500.woff2',
  './fonts/frank-hebrew-700.woff2',
  './fonts/frank-latin-500.woff2',
  './fonts/frank-latin-700.woff2',
];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put('./index.html', copy));
          return response;
        })
        .catch(() => caches.match('./index.html')),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      const refreshed = fetch(request)
        .then((response) => {
          if (response && response.status === 200 && response.type === 'basic') {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => cached);
      return cached || refreshed;
    }),
  );
});
